export function translate(language: Language, key: TranslationKey, variables: Record<string, string | number> = {}): string {
  const template = TRANSLATIONS[language]?.[key] ?? EN_TRANSLATIONS[key];
  return template.replace(/\{(\w+)\}/g, (match, variable: string) => String(variables[variable] ?? match));
}

export function translateCommandName(language: Language, commandId: string, englishName: string): string {
  return language === "ko" ? KO_COMMAND_NAMES[commandId] ?? englishName : englishName;
}

export function getCommandNameAliases(commandId: string, englishName: string): string[] {
  return [englishName, KO_COMMAND_NAMES[commandId] ?? englishName];
}

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && LANGUAGES.includes(value as Language);
}

export function isLanguagePreference(value: unknown): value is LanguagePreference {
  return value === "auto" || isLanguage(value);
}

export function resolveLanguage(preference: LanguagePreference, obsidianLocale: unknown): Language {
  if (isLanguage(preference)) {
    return preference;
  }
  return typeof obsidianLocale === "string" && /^ko(?:[-_]|$)/i.test(obsidianLocale) ? "ko" : "en";
}
